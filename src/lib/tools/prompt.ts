/** 도구별 "업무 도구 주문서" 프롬프트를 조립합니다. */
export function buildPrompt(tool: Tool): string {
  const situations = tool.situations
    .map((s) => {
      const options = s.options.map((o) => (o.includes("(기본)") ? o : `${o}${o === s.options[0] ? "(기본)" : ""}`));
      return `- [${s.label}] ${s.question} ${options.join(" / ")} / 직접 입력`;
    })
    .join("\n");

  const candidates = tool.candidates
    .map((g) => {
      const items = g.items
        .map((i) => `${i.star ? "★" : ""}${i.name}`)
        .join(" · ");
      return `- ${g.group}: ${items}`;
    })
    .join("\n");

  return `[업무 도구 주문서] ${tool.title} — 내 상황에 맞춰 만들어 주세요

아래 2단계로 진행해 주세요. 채팅이나 터미널에서 글로 묻거나 선택지를 띄우지 마세요. 고르는 일은 모두 「검토표 화면」에서 합니다.

1단계 · 검토표 화면 (지금 바로)
${tool.expert}의 눈으로 검토표 화면을 만들어 바로 띄워 주세요. 만들기 전에 지금 대화 내용과, 파일을 볼 수 있다면 지금 폴더의 파일을 살펴 제 업무 맥락을 파악하고, 맥락이 없으면 아래 「(기본)」 보기와 ★ 후보를 추천값으로 쓰세요. 띄운 뒤 채팅에는 이 한 줄만 남겨 주세요.
「열린 검토표에서 고른 뒤 [결정 복사하기]를 눌러 여기에 붙여 넣어 주세요.」
(화면을 띄울 수 없는 곳이라면 이 한 줄 대신 맨 아래 「화면 띄우는 법」의 안내를 따르세요.)

맥락에서 찾아볼 것 (있으면 검토표 추천값에 반영)
- 관련 파일·메일·메모가 있으면 → 예시 대신 그 내용으로 채우기
- 늘 반복되는 불편이나 「시간 부족」 같은 말이 보이면 → 관련 기능을 「적용 함」으로
- 함께 쓰는 사람 이름이 적혀 있으면 → 이름을 예시에 반영
- 우리 팀·회사 규칙(정시 종료·마감 시점 등)이 보이면 → 그 규칙에 맞추기

${REVIEW_COMMON}

② 「내 상황」 후보
${situations}

기본으로 꼭 들어갈 것
${tool.basics.map((b) => `- ${b}`).join("\n")}

검토표 후보 (★ = 맥락이 없을 때 기본으로 「적용 함」)
${candidates}

${HOW_TO_OPEN}

${COMMON_RULES}`;
}
